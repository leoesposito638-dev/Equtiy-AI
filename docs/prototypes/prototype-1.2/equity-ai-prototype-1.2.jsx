/* ----------------------------- APP ----------------------------- */

export default function EquityAIPrototype() {
  const [view, setView] = useState("dashboard");
  const [selectedTicker, setSelectedTicker] = useState(null);
  const [companyInitialTab, setCompanyInitialTab] = useState("overview");
  const [followed, setFollowed] = useState(new Set(["NVDA"]));
  const [recentSearches, setRecentSearches] = useState(["NVDA", "MSFT"]);
  const [mobileOpen, setMobileOpen] = useState(false);

  const goToCompany = (ticker, tab) => {
    setSelectedTicker(ticker);
    setCompanyInitialTab(tab || "overview");
    setView("company");
    setRecentSearches((prev) => [ticker, ...prev.filter((t) => t !== ticker)].slice(0, 3));
  };
  const goToSearch = () => setView("search");
  const toggleFollow = (ticker) => {
    setFollowed((prev) => {
      const next = new Set(prev);
      if (next.has(ticker)) next.delete(ticker); else next.add(ticker);
      return next;
    });
  };

  let page;
  if (view === "dashboard") page = <DashboardPage followed={followed} goToSearch={goToSearch} goToCompany={goToCompany} setView={setView} />;
  else if (view === "search") page = <SearchView recentSearches={recentSearches} goToCompany={goToCompany} />;
  else if (view === "company") page = <CompanyPage ticker={selectedTicker} followed={followed.has(selectedTicker)} onToggleFollow={() => toggleFollow(selectedTicker)} initialTab={companyInitialTab} onBack={() => setView("dashboard")} />;
  else if (view === "watchlist") page = <WatchlistPage followed={followed} goToCompany={goToCompany} />;
  else if (view === "companies") page = <CompaniesPage goToCompany={goToCompany} />;
  else if (view === "discover") page = <DiscoverPage followed={followed} goToCompany={goToCompany} />;
  else if (view === "alerts") page = <AlertsPage followed={followed} goToCompany={goToCompany} />;
  else if (view === "settings") page = <SettingsPage />;

  return (
    <div style={{ fontFamily: FONT, backgroundColor: C.bg, minHeight: "100vh", display: "flex", color: C.text }}>
      <Sidebar view={view} setView={setView} />
      <div style={{ flex: 1, minWidth: 0, display: "flex", flexDirection: "column" }}>
        <MobileTopBar view={view} setView={setView} mobileOpen={mobileOpen} setMobileOpen={setMobileOpen} />
        <div style={{ flex: 1, padding: "32px 24px 60px" }}>
          {page}
        </div>
      </div>
    </div>
  );
}

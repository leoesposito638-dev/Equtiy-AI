/* ----------------------------- SMALL PRIMITIVES ----------------------------- */

function ChangeTag({ value }) {
  const v = typeof value === "number" ? value : parseFloat(value);
  const isPos = v > 0, isZero = v === 0 || Number.isNaN(v);
  const color = isZero ? C.textFaint : isPos ? C.green : C.red;
  const Icon = isZero ? Minus : isPos ? ArrowUp : ArrowDown;
  return (
    <span style={{ display: "inline-flex", alignItems: "center", gap: 3, color, fontSize: 12.5, fontWeight: 600 }}>
      <Icon size={11} strokeWidth={2.5} />
      {isZero ? "0" : `${Math.abs(v)}${typeof value === "number" ? "" : ""}`}
    </span>
  );
}

function ColorDot({ color }) {
  const map = { green: C.green, yellow: C.yellow, red: C.red };
  return <span style={{ width: 7, height: 7, borderRadius: 999, backgroundColor: map[color], display: "inline-block", flexShrink: 0 }} />;
}

